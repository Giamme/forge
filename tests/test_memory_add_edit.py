    def test_edit_replaces_the_text_and_keeps_every_old_path(self):
        # Plain and --json must both write the same ledger. The spelling of the key is not the
        # ledger's; parse_forget_key folds it. src/b.py is column 12, src/a.py is only the anchor.
        for use_json in (False, True):
            self.write_ledger(EDIT_LEDGER)
            args = ['edit', str(self.repo), 'Trap:Cache_Ignores_Mtime', '--text', 'cache ignores inode',
                    '--path', 'src/c.py']
            if use_json:
                args.append('--json')
            done = self.memory(*args)
            self.assertEqual(done.returncode, 0, done.stderr)
            if use_json:
                self.assertEqual(json.loads(done.stdout), {
                    'ok': True,
                    'key': 'trap:cache ignores inode',
                    'memory_lines_added': ['- cache ignores inode [src/b.py]'],
                    'memory_lines_removed': ['- cache ignores mtime [src/a.py]'],
                })
            else:
                self.assertEqual(done.stdout, 'edited trap:cache ignores inode\n')
                self.assertEqual(done.stderr, '')
            ledger = self.ledger()
            self.assertTrue(ledger.startswith(HEADER + VERIFY), ledger)
            self.assertNotIn(b't1', ledger)
            self.assertNotIn(b't2', ledger)
            self.assertNotIn(b'cache ignores mtime', ledger)
            rows = self.data_rows()
            self.assertEqual(len(rows), 2)
            cols = rows[1]
            self.assertEqual(len(cols), 12)
            self.assertEqual(cols[2:7], ['-', 'person', '-', '-', 'trap'])
            self.assertRegex(cols[1], r'^manual-\d+$')
            self.assertEqual(cols[7], 'cache ignores inode')
            self.assertEqual(cols[8], 'cache ignores inode [src/b.py]')
            self.assertEqual(cols[9:], ['0', '1', 'src/b.py,src/a.py,src/c.py'])
            self.assertIn('- run the suite [Makefile]\n', self.memory_text())
            self.assertIn('- cache ignores inode [src/b.py]\n', self.memory_text())
            self.assertNotIn('mtime', self.memory_text())

