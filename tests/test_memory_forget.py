"""`forge memory forget`: drop ledger rows for a category:key and rebuild memory.md.

The kept ledger bytes, the rebuilt memory.md and the JSON a later forge-ui button reads are the
contract. Expected memory.md text is the document rebuild writes (header, then Verify, traps,
findings), not a second call to rebuild.
"""
import dataset_isolation  # noqa: F401  keeps the run dataset out of the developer's store
import json
import os
from pathlib import Path
import sqlite3
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
FORGE = str(ROOT / 'forge')

HEADER = (
    '# ts\trun_id\ttask\trole\tmodel\tverdict\tcategory\tkey\ttext\tduration_s\tinjectable\n'
).encode()


def row(ts, run, cat, key, text, nl=True):
    body = '\t'.join((ts, run, 't', 'dwarf', 'm', 'PASS', cat, key, text, '1', '1'))
    return (body + '\n').encode() if nl else body.encode()


# Two runs of one learning, other keys around it, a comment, and a last row with no newline.
ALPHA1 = row('2026-10-01T00:00:01Z', 'r1', 'trap', 'alpha thing', 'alpha thing [a.py]')
ALPHA2 = row('2026-10-02T00:00:02Z', 'r2', 'trap', 'alpha thing', 'alpha thing [a.py]')
BETA = row('2026-10-03T00:00:03Z', 'r1', 'trap', 'beta landmine', 'beta landmine [b.py]')
NOTE = b'# kept comment\n'
FINDING = row('2026-10-04T00:00:04Z', 'r1', 'finding', 'route added', 'route added [a.py]')
DASH = row('2026-10-05T00:00:05Z', 'r1', '-', '-', '-')
VERIFY = row('2026-10-06T00:00:06Z', 'r1', 'verify', 'run the suite', 'run the suite [Makefile]', nl=False)
FULL = HEADER + ALPHA1 + ALPHA2 + BETA + NOTE + FINDING + DASH + VERIFY
KEPT = HEADER + BETA + NOTE + FINDING + DASH + VERIFY
# The only trap, so forgetting it drops the whole Known traps section.
ONLY_TRAP = HEADER + ALPHA1 + VERIFY


def rebuilt(*sections):
    text = (
        '# forge project memory\n'
        '<!-- Maintained by forge from what its own runs observed. Do not edit this file\n'
        '     inside a dwarf run: it is excluded from every diff and your edit would be\n'
        '     overwritten. Facts only, one per line. -->\n'
        '\n'
    )
    for title, facts in sections:
        text += title + '\n'
        for fact in facts:
            text += fact + '\n'
        text += '\n'
    return text


MEMORY_BETA = rebuilt(
    ('## Verify', ['- run the suite [Makefile]']),
    ('## Known traps', ['- beta landmine [b.py]']),
)
MEMORY_BOTH = rebuilt(
    ('## Verify', ['- run the suite [Makefile]']),
    ('## Known traps', ['- alpha thing [a.py]']),
)
MEMORY_VERIFY = rebuilt(
    ('## Verify', ['- run the suite [Makefile]']),
)
ALPHA_LINE = '- alpha thing [a.py]'


class ForgetTests(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.base = Path(tmp.name)
        self.repo = self.base / 'repo'
        self.repo.mkdir()
        (self.repo / 'a.py').write_text('x = 1\n')
        (self.repo / 'b.py').write_text('y = 2\n')
        (self.repo / 'Makefile').write_text('all:\n')
        self.home = self.base / 'data'
        # A store under a forge worktree is refused, so an event test there would pass for
        # the wrong reason. tempfile lands outside this checkout.
        self.assertNotIn('.forge-worktrees', self.home.resolve().parts)
        self.env = dict(os.environ, FORGE_DATASET='off', FORGE_DATA_HOME=str(self.home),
                        FORGE_MEMORY='on', FORGE_MEMORY_MAX_LINES='40', FORGE_MEMORY_MAX_BYTES='4096',
                        XDG_CONFIG_HOME=str(self.base / 'cfg'))
        self.env.pop('FORGE_MEMORY_DEEP_PRUNE', None)
        self.write_ledger(FULL)

    def write_ledger(self, data, memory=None):
        forge = self.repo / '.forge'
        forge.mkdir(exist_ok=True)
        (forge / 'ledger.tsv').write_bytes(data)
        mem = forge / 'memory.md'
        if memory is None:
            if mem.exists():
                mem.unlink()
        else:
            mem.write_text(memory)

    def ledger(self):
        return (self.repo / '.forge' / 'ledger.tsv').read_bytes()

    def forge_files(self):
        root = self.repo / '.forge'
        found = {}
        for path in sorted(root.rglob('*')):
            rel = str(path.relative_to(root))
            if path.is_file():
                found[rel] = (path.stat().st_mtime_ns, path.read_bytes())
            else:
                found[rel] = ('dir', None)
        return found

    def forget(self, *args, env=None):
        return subprocess.run([FORGE, 'memory', 'forget', str(self.repo), *args],
                              capture_output=True, text=True, env=env or self.env)

    def launch(self, *args):
        return subprocess.run([FORGE, *args], capture_output=True, text=True, env=self.env)

    def memory_events(self, home=None):
        path = Path(home or self.home) / 'dataset' / 'dataset.sqlite'
        if not path.exists():
            return []
        db = sqlite3.connect(str(path))
        try:
            rows = db.execute("SELECT data FROM events WHERE kind = 'event' ORDER BY ts, rid").fetchall()
        finally:
            db.close()
        return [json.loads(row[0]) for row in rows if json.loads(row[0]).get('name') == 'memory_forget']

    def test_forgetting_a_key_removes_only_its_rows_and_rebuilds_memory(self):
        # Trap:Alpha_Thing is the ledger's normalised trap / alpha thing. Both runs go; every
        # other byte, including the last line with no newline, stays in order.
        done = self.forget('Trap:Alpha_Thing')
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertEqual(done.stdout, 'trap:alpha thing\t2\n')
        self.assertEqual(self.ledger(), KEPT)
        self.assertEqual((self.repo / '.forge' / 'memory.md').read_text(), MEMORY_BETA)
        self.assertNotIn('alpha thing', (self.repo / '.forge' / 'memory.md').read_text())

    def test_json_shape_lists_the_fact_lines_that_left_with_no_memory_file_present(self):
        # No memory.md on disk: the lines still come from a rebuild of the full ledger.
        done = self.forget('Trap:Alpha_Thing', '--json')
        self.assertEqual(done.returncode, 0, done.stderr)
        body = json.loads(done.stdout)
        self.assertEqual(set(body), {'ok', 'dry_run', 'keys', 'memory_lines_removed'})
        self.assertIs(body['ok'], True)
        self.assertIs(body['dry_run'], False)
        self.assertEqual(body['keys'], [{'key': 'trap:alpha thing', 'rows': 2, 'found': True}])
        self.assertEqual(body['memory_lines_removed'], [ALPHA_LINE])
        self.assertTrue(all(line.startswith('- ') for line in body['memory_lines_removed']))
        self.assertEqual((self.repo / '.forge' / 'memory.md').read_text(), MEMORY_BETA)

    def test_dry_run_reports_the_same_rows_and_lines_and_writes_nothing(self):
        before = self.forge_files()
        dry = self.forget('Trap:Alpha_Thing', '--dry-run', '--json')
        self.assertEqual(dry.returncode, 0, dry.stderr)
        self.assertEqual(self.forge_files(), before)
        preview = json.loads(dry.stdout)
        self.assertIs(preview['dry_run'], True)
        real = self.forget('Trap:Alpha_Thing', '--json')
        self.assertEqual(real.returncode, 0, real.stderr)
        body = json.loads(real.stdout)
        self.assertEqual(preview['keys'], body['keys'])
        self.assertEqual(preview['memory_lines_removed'], body['memory_lines_removed'])
        self.assertEqual(body['memory_lines_removed'], [ALPHA_LINE])
        self.assertEqual(self.ledger(), KEPT)

    def test_a_hand_edited_memory_does_not_change_the_reported_lines(self):
        self.write_ledger(ONLY_TRAP, memory='# edited by hand\n- handmade noise\n')
        before = self.forge_files()
        dry = self.forget('trap:alpha thing', '--dry-run', '--json')
        self.assertEqual(dry.returncode, 0, dry.stderr)
        self.assertEqual(json.loads(dry.stdout)['memory_lines_removed'], [ALPHA_LINE])
        self.assertEqual(self.forge_files(), before)
        real = self.forget('trap:alpha thing', '--json')
        self.assertEqual(real.returncode, 0, real.stderr)
        body = json.loads(real.stdout)
        self.assertEqual(body['memory_lines_removed'], [ALPHA_LINE])
        self.assertNotIn('handmade', '\n'.join(body['memory_lines_removed']))
        self.assertEqual((self.repo / '.forge' / 'memory.md').read_text(), MEMORY_VERIFY)
        self.assertEqual(self.ledger(), HEADER + VERIFY)

    def test_a_disappearing_section_heading_is_not_a_removed_line(self):
        # The on-disk memory.md is what a rebuild would have written, so the heading really
        # does leave the file. The report still lists only the fact line.
        self.write_ledger(ONLY_TRAP, memory=MEMORY_BOTH)
        done = self.forget('trap:alpha thing', '--json')
        self.assertEqual(done.returncode, 0, done.stderr)
        body = json.loads(done.stdout)
        self.assertEqual(body['memory_lines_removed'], [ALPHA_LINE])
        self.assertNotIn('## Known traps', body['memory_lines_removed'])
        self.assertEqual((self.repo / '.forge' / 'memory.md').read_text(), MEMORY_VERIFY)

    def test_an_unknown_key_is_not_an_error(self):
        text = self.forget('trap:no such thing')
        self.assertEqual(text.returncode, 0, text.stderr)
        self.assertEqual(text.stdout, 'trap:no such thing\tnot found\n')
        body = json.loads(self.forget('trap:no such thing', '--json').stdout)
        self.assertEqual(body['keys'], [{'key': 'trap:no such thing', 'rows': 0, 'found': False}])
        self.assertEqual(body['memory_lines_removed'], [])
        self.assertEqual(self.ledger(), FULL)
        self.assertFalse((self.repo / '.forge' / 'memory.md').exists())
        # A colon after the first one belongs to the key. It is not a usage error.
        extra = json.loads(self.forget('trap:key:extra', '--json').stdout)
        self.assertEqual(extra['keys'], [{'key': 'trap:key extra', 'rows': 0, 'found': False}])
        self.assertEqual(self.ledger(), FULL)
        empty = self.base / 'empty'
        empty.mkdir()
        missing = subprocess.run([FORGE, 'memory', 'forget', str(empty), 'trap:alpha', '--json'],
                                 capture_output=True, text=True, env=self.env)
        self.assertEqual(missing.returncode, 0, missing.stderr)
        self.assertEqual(json.loads(missing.stdout)['keys'],
                         [{'key': 'trap:alpha', 'rows': 0, 'found': False}])
        self.assertFalse((empty / '.forge').exists())

    def test_a_bad_key_or_actor_exits_2_and_leaves_the_ledger(self):
        for key in ('nocolon', 'trap:', ':alpha', ':', 'trap:   ', ':::'):
            done = self.forget(key)
            self.assertEqual(done.returncode, 2, key)
            self.assertIn('category:key', done.stderr)
            self.assertEqual(self.ledger(), FULL)
        for args in (('--actor', 'person'), ('--actor',), ('--actor', 'UI')):
            done = self.forget('Trap:Alpha_Thing', *args)
            self.assertEqual(done.returncode, 2, args)
            self.assertIn('actor', done.stderr)
            self.assertEqual(self.ledger(), FULL)
        bare = self.launch('memory', 'forget', str(self.repo))
        self.assertEqual(bare.returncode, 2)
        self.assertEqual(bare.stdout, '')
        self.assertEqual(self.ledger(), FULL)

    def test_dataset_event_names_each_key_once_and_is_skipped_otherwise(self):
        live = dict(self.env, FORGE_DATASET='on')
        miss = self.forget('trap:missing', '--json', env=live)
        self.assertEqual(miss.returncode, 0, miss.stderr)
        self.assertEqual(self.memory_events(), [])
        done = self.forget('Trap:Alpha_Thing', 'trap:beta landmine', 'Trap:Alpha_Thing', '--json', env=live)
        self.assertEqual(done.returncode, 0, done.stderr)
        body = json.loads(done.stdout)
        self.assertEqual(body['keys'], [
            {'key': 'trap:alpha thing', 'rows': 2, 'found': True},
            {'key': 'trap:beta landmine', 'rows': 1, 'found': True},
        ])
        self.assertEqual(body['memory_lines_removed'], [ALPHA_LINE, '- beta landmine [b.py]'])
        [event] = self.memory_events()
        self.assertEqual(event['name'], 'memory_forget')
        self.assertEqual(event['keys'], 'trap:alpha thing,trap:beta landmine')
        self.assertEqual(event['rows'], '3')
        self.assertEqual(event['actor'], 'cli')
        ui = self.forget('finding:route added', '--actor', 'ui', '--json', env=live)
        self.assertEqual(ui.returncode, 0, ui.stderr)
        self.assertEqual(json.loads(ui.stdout)['memory_lines_removed'], [])
        self.assertEqual(self.memory_events()[-1]['actor'], 'ui')
        self.assertEqual(self.memory_events()[-1]['keys'], 'finding:route added')
        self.assertEqual(self.memory_events()[-1]['rows'], '1')

        self.write_ledger(FULL)
        off_home = self.base / 'off-data'
        off = self.forget('Trap:Alpha_Thing', env=dict(self.env, FORGE_DATASET='off', FORGE_DATA_HOME=str(off_home)))
        self.assertEqual(off.returncode, 0, off.stderr)
        self.assertEqual(self.ledger(), KEPT)
        self.assertFalse((off_home / 'dataset' / 'dataset.sqlite').exists())

    def test_launcher_lists_forget_with_the_other_memory_commands(self):
        helped = self.launch('memory', 'forget', '--help')
        usage = self.launch('memory', '--help')
        self.assertEqual(helped.returncode, 0, helped.stderr)
        self.assertEqual(helped.stdout, usage.stdout)
        self.assertIn('forget <repo>', helped.stdout)
        bare = self.launch('memory', 'forget')
        self.assertEqual((bare.returncode, bare.stdout), (2, ''))
        self.assertIn('category:key', bare.stderr)
        nope = self.launch('memory', 'nope')
        self.assertEqual(nope.returncode, 2)
        self.assertIn('show, learnings, prune, spend, inject or forget', nope.stderr)


if __name__ == '__main__':
    unittest.main()
